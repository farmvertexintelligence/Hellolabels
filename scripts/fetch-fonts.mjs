// Downloads the open-licence (SIL OFL) fonts used by the site and the label designer.
//  - assets/fonts/*.ttf   → used by the server print renderer (resvg) for PDFs
//  - public/fonts/*.woff2 + public/fonts/fonts.css → used by browsers (subset by unicode-range)
// Run once with `npm run fonts`; the output is committed so builds need no network.
import fs from "node:fs/promises";
import path from "node:path";

export const FAMILIES = [
  ["Fraunces", [400, 600, 700]],
  ["DM Sans", [400, 500, 700]],
  ["Playfair Display", [400, 700]],
  ["Cinzel", [400, 700]],
  ["Great Vibes", [400]],
  ["Poppins", [400, 600, 800]],
  ["Oswald", [500, 700]],
  ["Noto Sans Tamil", [400, 600, 700]],
  ["Noto Serif Tamil", [400, 700]],
  ["Arima", [400, 700]],
  ["Baloo Thambi 2", [500, 800]],
  ["Mukta Malar", [400, 700]],
];

const root = path.resolve(new URL(".", import.meta.url).pathname, "..");
const ttfDir = path.join(root, "assets/fonts");
const webDir = path.join(root, "public/fonts");
const MODERN_UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36";

const slug = (s) => s.toLowerCase().replace(/\s+/g, "-");

async function css(family, weights, ua) {
  const url = `https://fonts.googleapis.com/css2?family=${encodeURIComponent(family)}:wght@${weights.join(";")}&display=swap`;
  const res = await fetch(url, { headers: ua ? { "user-agent": ua } : {} });
  if (!res.ok) throw new Error(`${family}: ${res.status}`);
  return res.text();
}

async function download(url, file) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: ${res.status}`);
  await fs.writeFile(file, Buffer.from(await res.arrayBuffer()));
}

const pending = [];
await fs.mkdir(ttfDir, { recursive: true });
await fs.mkdir(webDir, { recursive: true });
let webCss = "/* Generated by scripts/fetch-fonts.mjs — SIL Open Font Licence fonts from Google Fonts */\n";

for (const [family, weights] of FAMILIES) {
  // TTF (no user agent → Google serves truetype, one file per weight)
  const ttfCss = await css(family, weights);
  for (const block of ttfCss.split("@font-face").slice(1)) {
    const weight = block.match(/font-weight:\s*(\d+)/)[1];
    const src = block.match(/url\((.+?)\)/)[1];
    await download(src, path.join(ttfDir, `${slug(family)}-${weight}.ttf`));
  }
  // WOFF2 subsets for the web
  const wCss = await css(family, weights, MODERN_UA);
  let i = 0;
  webCss += wCss.replace(/url\((https:[^)]+\.woff2)\)/g, (_m, u) => {
    const name = `${slug(family)}-${i++}.woff2`;
    pending.push(download(u, path.join(webDir, name)));
    return `url(/fonts/${name})`;
  });
  await Promise.all(pending.splice(0));
  console.log("✓", family);
}



// Split into the always-loaded UI fonts and the designer-only label fonts.
const CORE = new Set(["Fraunces", "DM Sans", "Noto Sans Tamil", "Noto Serif Tamil"]);
const blocks = webCss.match(/(\/\*[^*]*\*\/\s*)?@font-face\s*{[^}]*}/g) ?? [];
const pick = (core) => blocks.filter((b) => CORE.has(b.match(/font-family:\s*'([^']+)'/)[1]) === core).join("\n");
await fs.writeFile(path.join(webDir, "core.css"), pick(true));
await fs.writeFile(path.join(webDir, "label.css"), pick(false));
